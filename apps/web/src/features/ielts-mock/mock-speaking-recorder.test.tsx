import '@testing-library/jest-dom/vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { useAudioRecorder } from '../learning-session/use-audio-recorder';
import { ieltsMockClient } from '../../lib/api/ielts-mock-client';
import { normalizeRecordingWav } from './recording-wav';
import { MockSpeakingRecorder } from './mock-speaking-recorder';
vi.mock('./recording-wav',()=>({normalizeRecordingWav:vi.fn(async(blob:Blob)=>blob)}));
vi.mock('../learning-session/use-audio-recorder', () => ({ useAudioRecorder: vi.fn() }));
vi.mock('../../lib/api/ielts-mock-client', () => ({ ieltsMockClient: { uploadRecording: vi.fn() } }));
afterEach(cleanup);
it('requires consent before microphone use and keeps an upload ID through a network retry', async () => {
  const start = vi.fn();
  const state = { blob: null, previewUrl: null, status: 'idle', supported: true, error: null, start, stop: vi.fn(), discard: vi.fn(), mimeType: 'audio/wav' };
  vi.mocked(useAudioRecorder).mockReturnValue(state as ReturnType<typeof useAudioRecorder>);
  const props = { attemptId: 'attempt', part: { part: 1, title: 'Interview', prompts: ['Where do you live?'], preparationSeconds: 0, responseSeconds: 240 }, paused: false, saved: undefined, onSaved: vi.fn() };
  const view = render(<MockSpeakingRecorder {...props} />);
  expect(screen.getByRole('button', { name: 'Record answer' })).toBeDisabled();
  fireEvent.click(screen.getByRole('checkbox'));
  fireEvent.click(screen.getByRole('button', { name: 'Record answer' }));
  expect(start).toHaveBeenCalledOnce();
  vi.mocked(useAudioRecorder).mockReturnValue({ ...state, status: 'preview', blob: new Blob(['captured'], { type: 'audio/wav' }), previewUrl: 'blob:preview' } as ReturnType<typeof useAudioRecorder>);
  vi.mocked(ieltsMockClient.uploadRecording).mockRejectedValueOnce(new Error('offline')).mockResolvedValue({ id: 'recording', part: 1, durationSeconds: 2, createdAt: new Date().toISOString() });
  view.rerender(<MockSpeakingRecorder {...props} />);
  fireEvent.click(screen.getByRole('button', { name: 'Upload answer' }));
  expect(await screen.findByRole('alert')).toBeVisible();
  fireEvent.click(screen.getByRole('button', { name: 'Upload answer' }));
  await waitFor(() => expect(props.onSaved).toHaveBeenCalledOnce());
  expect(normalizeRecordingWav).toHaveBeenLastCalledWith(expect.any(Blob),240);
  const calls = vi.mocked(ieltsMockClient.uploadRecording).mock.calls;
  expect(calls[0]?.[1].get('clientRecordingId')).toBe(calls[1]?.[1].get('clientRecordingId'));
  expect(calls[1]?.[1].get('consent')).toBe('true');
});
